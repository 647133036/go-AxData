// Package source provides the data source adapter registry and provider interface declarations.
// Mirrors the upstream axdata-provider.json declaration pattern from AxData Python.
package source

import (
	"github.com/electkismet/axdata-go/core/schema"
)

// LookupOk retrieves an adapter by name and reports whether it was found.
func LookupOk(name string) (Adapter, bool) {
	a := Lookup(name)
	return a, a != nil
}

// ─── Provider Interface Registry ────────────────────────────────────────

// ProviderInterface declares a source interface and its collector output contract.
// Mirrors axdata-provider.json interfaces + _TDX_LOGICAL_TABLES collector mapping.
type ProviderInterface struct {
	Name        string // interface name, e.g. "stock_codes_tdx"
	SourceCode  string // source code, e.g. "tdx"
	DisplayName string
	Description string

	Table       string // output table name (must exist in schema.TableRegistry)
	Layer       string // output layer, e.g. "core"
	WriteMode   string // write mode from table schema

	// FieldMapping maps adapter output field names → table column names.
	// If nil, direct field name match is used.
	// Format: map[adapter_field_name]table_column_name
	FieldMapping map[string]string
}

