// GetOutputTable returns the output table name for an interface.
func GetOutputTable(name string) string {
	if pi := ProviderRegistry[name]; pi != nil {
		return pi.Table
	}
	return ""
}

// GetOutputLayer returns the output layer for an interface.
func GetOutputLayer(name string) string {
	if pi := ProviderRegistry[name]; pi != nil {
		return pi.Layer
	}
	return "core"
}

// InterfaceNames returns all registered provider interface names.
func InterfaceNames() []string {
	names := make([]string, 0, len(ProviderRegistry))
	for name := range ProviderRegistry {
		names = append(names, name)
	}
	return names
}

// InferSchema attempts to derive a TableSchema from a ProviderInterface's FieldMapping.
func (pi *ProviderInterface) InferSchema() *schema.TableSchema {
	if len(pi.FieldMapping) == 0 {
		return nil
	}
	cols := make([]schema.ColumnSchema, 0, len(pi.FieldMapping))
	for _, colName := range pi.FieldMapping {
		cols = append(cols, schema.ColumnSchema{
			Name: colName,
			Type: "string",
		})
	}
	return &schema.TableSchema{
		Name:        pi.Name,
		Columns:     cols,
		Description: pi.Description,
		Layer:       pi.Layer,
		WriteMode:   pi.WriteMode,
	}
}
